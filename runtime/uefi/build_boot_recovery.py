"""Build the independent relocation-free EFISP recovery module; no device I/O."""
from pathlib import Path
import argparse
import base64
import hashlib
import json
import os
import re
import subprocess
from elftools.elf.elffile import ELFFile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
NDK = Path(os.environ.get("ANDROID_NDK_HOME", "D:/AndroidSDK/ndk/android-ndk-r29"))
LLVM = NDK / "toolchains/llvm/prebuilt/windows-x86_64/bin"
SYMBOLS = {
    "ENTRY": "br_entry", "REQUEST": "br_request", "FORCED": "br_forced",
    "MARK_ONLY": "br_mark_only", "MANUAL_ALLOWED": "br_manual_allowed",
    "BOOTLINUX": "br_bootlinux", "SET_ACTIVE": "br_set_active",
    "DEFER": "br_defer", "PENDING": "br_pending", "PENDING_VALUE": "br_pending_value",
    "BOOT_SCOPE": "br_boot_scope", "FASTBOOT_ENTER": "br_fastboot_enter", "AUTH": "br_auth",
    "ORIGINAL_ENTRY": "br_original_entry", "CONFIG": "br_config",
}

def run(args):
    completed = subprocess.run([str(x) for x in args], capture_output=True, text=True)
    if completed.returncode:
        raise RuntimeError(completed.stdout + completed.stderr)

def main(output):
    output.mkdir(parents=True, exist_ok=True)
    common = [LLVM / "clang.exe", "--target=aarch64-none-elf", "-O2",
              "-ffreestanding", "-fno-builtin", "-fno-stack-protector", "-fPIC",
              "-fvisibility=hidden", "-ffixed-x18", "-mgeneral-regs-only",
              "-fno-jump-tables", "-fno-unwind-tables", "-fno-asynchronous-unwind-tables",
              "-mbranch-protection=standard", "-Wall", "-Wextra", "-Werror"]
    c_obj, s_obj, elf = output / "recovery-c.o", output / "recovery-asm.o", output / "recovery.elf"
    run(common + ["-std=c11", "-c", HERE / "boot_recovery.c", "-o", c_obj])
    assembly = [argument for argument in common if argument != "-mgeneral-regs-only"]
    run(assembly + ["-c", HERE / "boot_recovery.S", "-o", s_obj])
    run([LLVM / "ld.lld.exe", "-T", HERE / "boot_recovery.ld",
         "--no-undefined", "--fatal-warnings", s_obj, c_obj, "-o", elf])
    with elf.open("rb") as stream:
        binary = ELFFile(stream)
        symbols = {s.name: int(s["st_value"]) for s in binary.get_section_by_name(".symtab").iter_symbols()}
        unresolved = [s.name for s in binary.get_section_by_name(".symtab").iter_symbols()
                      if s.name and s["st_shndx"] == "SHN_UNDEF"]
        relocations = [s.name for s in binary.iter_sections()
                       if s["sh_type"] in ("SHT_REL", "SHT_RELA", "SHT_DYNAMIC")]
        mutable = [s.name for s in binary.iter_sections()
                   if s.name in (".data", ".bss", ".got", ".got.plt") and s["sh_size"]]
        assert not unresolved and not relocations and not mutable
        data = binary.get_section_by_name(".module").data()
        assert binary["e_entry"] == symbols["br_entry"] == 0
    offsets = {key: symbols[value] for key, value in SYMBOLS.items()}
    assert data[offsets["CONFIG"]:offsets["CONFIG"] + 256] == bytes(256)
    digest = hashlib.sha256(data).hexdigest()
    (output / "recovery.bin").write_bytes(data)
    encoded = base64.b64encode(data).decode()
    declarations = "\n".join(f"    const val {key}_OFFSET = {value}L" for key, value in offsets.items())
    chunks = "\n".join('        "' + encoded[i:i+120] + '"' +
                       (" +" if i + 120 < len(encoded) else "") for i in range(0, len(encoded), 120))
    source = ("package net.hawyn.ablefisp.patch\n\n"
              "// Generated by runtime/uefi/build_boot_recovery.py; PIC, no imports or relocations.\n"
              "internal object FastbootRecoveryModule {\n"
              f'    const val SHA256 = "{digest}"\n'
              "    const val CONFIG_BYTES = 256\n"
              "    const val STATE_BYTES = 4096\n" +
              "    const val STATE_BOOT_SCOPE_OFFSET = " + re.search(r"^#define BR_STATE_BOOT_SCOPE (\d+)$", (HERE / "boot_recovery.h").read_text(), re.M).group(1) + "L\n" +
              declarations + "\n"
              "    val bytes: ByteArray get() = java.util.Base64.getDecoder().decode(\n" +
              chunks + "\n    )\n}\n")
    destination = ROOT / "abl-efisp-core/src/main/kotlin/net/hawyn/ablefisp/patch/FastbootRecoveryModule.kt"
    destination.write_text(source, encoding="utf-8")
    manifest = {"bytes": len(data), "sha256": digest, "offsets": offsets,
                "undefined": unresolved, "relocations": relocations, "mutableSections": mutable,
                "deviceOperations": False, "sourcesSha256": {
                    str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
                    for path in (HERE / "boot_recovery.h", HERE / "boot_recovery.c",
                                 HERE / "boot_recovery.S", HERE / "boot_recovery.ld")}}
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(manifest))

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "build/boot-recovery")
    main(parser.parse_args().output.resolve())
