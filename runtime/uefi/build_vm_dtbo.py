"""Build the bounded VM DTBO reader as relocation-free ARM64 PIC."""
from pathlib import Path
import argparse,base64,hashlib,json,os,subprocess
from elftools.elf.elffile import ELFFile
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
LLVM=Path(os.environ.get('ANDROID_NDK_HOME','D:/AndroidSDK/ndk/android-ndk-r29'))/'toolchains/llvm/prebuilt/windows-x86_64/bin'
def main(out):
    out.mkdir(parents=True,exist_ok=True)
    obj,elf=out/'vm_dtbo.o',out/'vm_dtbo.elf'
    flags=['--target=aarch64-none-elf','-O2','-ffreestanding','-fno-builtin','-fno-stack-protector',
        '-fPIC','-fvisibility=hidden','-ffixed-x18','-mgeneral-regs-only','-fno-jump-tables',
        '-fno-unwind-tables','-fno-asynchronous-unwind-tables','-mbranch-protection=standard',
        '-Wall','-Wextra','-Werror']
    for cmd in ([LLVM/'clang.exe',*flags,'-c',HERE/'vm_dtbo.c','-o',obj],
                [LLVM/'ld.lld.exe','-T',HERE/'vm_dtbo.ld','--no-undefined','--fatal-warnings',obj,'-o',elf]):
        subprocess.run(list(map(str,cmd)),check=True,capture_output=True)
    with elf.open('rb') as f:
        e=ELFFile(f);sections=list(e.iter_sections())
        undefined=[s.name for s in e.get_section_by_name('.symtab').iter_symbols() if s.name and s['st_shndx']=='SHN_UNDEF']
        reloc=[s.name for s in sections if s['sh_type'] in ('SHT_REL','SHT_RELA','SHT_DYNAMIC')]
        mutable=[s.name for s in sections if s.name in ('.data','.bss','.got','.got.plt') and s['sh_size']]
        assert not undefined and not reloc and not mutable
        data=e.get_section_by_name('.module').data()
        symbols={s.name:int(s['st_value']) for s in e.get_section_by_name('.symtab').iter_symbols()}
    (out/'vm_dtbo.bin').write_bytes(data)
    sha=hashlib.sha256(data).hexdigest();encoded=base64.b64encode(data).decode()
    destination=ROOT/'abl-efisp-core/src/main/kotlin/net/hawyn/ablefisp/patch/VmDtboCompatModule.kt'
    destination.write_text('package net.hawyn.ablefisp.patch\n\n// Generated by runtime/uefi/build_vm_dtbo.py; bounded PIC reader, no firmware I/O.\ninternal object VmDtboCompatModule {\n'+
        f'    const val SHA256 = "{sha}"\n    const val ENTRY_OFFSET = {symbols["vm_dtbo_select"]}L\n'+
        '    val bytes: ByteArray get() = java.util.Base64.getDecoder().decode(\n'+
        ' +\n'.join('        "'+encoded[i:i+120]+'"' for i in range(0,len(encoded),120))+'\n    )\n}\n',encoding='utf-8')
    report={'bytes':len(data),'sha256':sha,'entry':symbols['vm_dtbo_select'],'undefined':undefined,
        'relocations':reloc,'mutableSections':mutable,'sourcesSha256':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in [HERE/'vm_dtbo.c',HERE/'vm_dtbo.h',HERE/'vm_dtbo.ld']},'deviceOperations':False}
    (out/'vm_dtbo.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report))
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--output',type=Path,default=ROOT/'build/vm-dtbo');main(p.parse_args().output)
