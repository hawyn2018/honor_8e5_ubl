"""Reproducible PIC module builder. No firmware or device writes."""
from pathlib import Path
import subprocess, hashlib, base64, json
from elftools.elf.elffile import ELFFile
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
OUT=ROOT/'build'/'kbl-parent'
LLVM=Path('D:/AndroidSDK/ndk/android-ndk-r29/toolchains/llvm/prebuilt/windows-x86_64/bin')
def run(args):
 p=subprocess.run([str(x) for x in args],capture_output=True,text=True)
 if p.returncode: raise RuntimeError(p.stdout+p.stderr)
 return p.stdout
def main(output=None):
 global OUT
 if output is not None:OUT=Path(output).resolve()
 OUT.mkdir(parents=True,exist_ok=True)
 obj=OUT/'parent.o'; elf=OUT/'parent.elf'; blob=OUT/'parent.bin'
 run([LLVM/'clang.exe','--target=aarch64-none-elf','-O2','-std=c11','-Wall','-Wextra','-Werror',
 '-ffreestanding','-fno-builtin','-fno-stack-protector','-fPIC','-fvisibility=hidden','-ffixed-x18',
 '-mgeneral-regs-only','-fno-jump-tables','-fno-unwind-tables','-fno-asynchronous-unwind-tables',
 '-c',HERE/'kbl_parent_shim.c','-o',obj])
 run([LLVM/'ld.lld.exe','-T',HERE/'kbl_parent_shim.ld','--no-undefined','--fatal-warnings',obj,'-o',elf])
 with elf.open('rb') as f:
  e=ELFFile(f); sym=e.get_section_by_name('.symtab')
  assert not [s.name for s in sym.iter_symbols() if s.name and s['st_shndx']=='SHN_UNDEF']
  assert not [s.name for s in e.iter_sections() if s['sh_type'] in ('SHT_REL','SHT_RELA','SHT_DYNAMIC')]
  assert e['e_entry']==0
  assert not any(s['sh_size'] for s in e.iter_sections() if s.name in ('.bss','.data','.got','.got.plt'))
  data=e.get_section_by_name('.module').data()
  lazy_entry=next(s['st_value'] for s in sym.iter_symbols() if s.name=='kbl_parent_lazy_start')
 blob.write_bytes(data)
 sha=hashlib.sha256(data).hexdigest()
 dest=ROOT/'abl-efisp-core/src/main/kotlin/net/hawyn/ablefisp/patch/KblParentModule.kt'
 b64=base64.b64encode(data).decode()
 dest.write_text('package net.hawyn.ablefisp.patch\n\n// Generated by runtime/uefi/build_parent_shim.py; PIC, no relocation/import.\ninternal object KblParentModule {\n    const val SHA256 = "'+sha+'"\n    const val LAZY_START_OFFSET = '+str(lazy_entry)+'L\n    val bytes: ByteArray get() = java.util.Base64.getDecoder().decode(\n'+
 '\n'.join('        "'+b64[i:i+120]+'"'+(' +' if i+120<len(b64) else '') for i in range(0,len(b64),120))+'\n    )\n}\n',encoding='utf-8')
 report={'bytes':len(data),'sha256':sha,'entry':0,'lazy_start_offset':lazy_entry,'undefined':0,'dynamic_relocations':0,'mutable_sections':0,
 'sources_sha256':{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in
 [HERE/'kbl_parent_shim.c',HERE/'kbl_parent_shim.h',HERE/'kbl_parent_shim.ld',HERE/'kbl_service.h']}}
 (OUT/'manifest.json').write_text(json.dumps(report,indent=2))
 print(json.dumps(report))
if __name__=='__main__':
 import argparse
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--output',type=Path,default=OUT)
 main(parser.parse_args().output)
